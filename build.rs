use std::fmt::Write as FmtWrite;
use std::path::PathBuf;

const BACKOFF_INFO: &[(&str, &str)] = &[
    ("crossbeam", "backoff::Crossbeam"),
    ("yield", "backoff::Yield"),
];

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    generate_queue_variants();

    if std::env::var("CARGO_FEATURE_BENCH_MOODYCAMEL").is_ok() {
        println!("cargo:rerun-if-changed=third_party/moodycamel/shim.cpp");
        println!("cargo:rerun-if-changed=third_party/moodycamel/concurrentqueue.h");
        cc::Build::new()
            .cpp(true)
            .file("third_party/moodycamel/shim.cpp")
            .include("third_party/moodycamel")
            .std("c++17")
            .compile("moodycamel_shim");
    }

    let out_dir = std::env::var("OUT_DIR").expect("OUT_DIR not set");
    let path = PathBuf::from(&out_dir).join("bench_registry.rs");

    let feature_enabled = std::env::var("CARGO_FEATURE_BENCH_REGISTRY").is_ok();
    if !feature_enabled {
        // Write a stub so the include! always succeeds.
        std::fs::write(
            path,
            "// bench_registry feature not enabled — stub only.\n\
             fn lookup_ubq_job_factory(\n\
             \x20\x20\x20\x20_label: &str,\n\
             \x20\x20\x20\x20_scenario: ScenarioConfig,\n\
             \x20\x20\x20\x20_repeat_index: usize,\n\
             \x20\x20\x20\x20_mode: Mode,\n\
             \x20\x20\x20\x20_items_per_producer: u64,\n\
             \x20\x20\x20\x20_batch_size: Option<usize>,\n\
             ) -> Option<JobFactory> { None }\n\
             fn lookup_ubq_handoff_profile(\n\
             \x20\x20\x20\x20_label: &str,\n\
             \x20\x20\x20\x20_config: &HandoffProfileConfig,\n\
             ) -> Option<Result<HandoffProfileResult, String>> { None }\n",
        )
        .expect("failed to write bench_registry.rs stub");
        return;
    }

    let mut code = String::with_capacity(256 * 1024);
    writeln!(code, "// Auto-generated by build.rs — do not edit.").unwrap();
    writeln!(code, "fn lookup_ubq_job_factory(").unwrap();
    writeln!(code, "    label: &str,").unwrap();
    writeln!(code, "    scenario: ScenarioConfig,").unwrap();
    writeln!(code, "    repeat_index: usize,").unwrap();
    writeln!(code, "    mode: Mode,").unwrap();
    writeln!(code, "    items_per_producer: u64,").unwrap();
    writeln!(code, "    batch_size: Option<usize>,").unwrap();
    writeln!(code, ") -> Option<JobFactory> {{").unwrap();
    writeln!(code, "    match label {{").unwrap();

    for &(backoff_name, backoff_ty) in BACKOFF_INFO {
        let label_str = format!("balanced,1,page,{backoff_name}");
        let value_type_expr = format!("UBQ<u64, {backoff_ty}>");
        let log_type_expr = format!("UBQ<LogRecord, {backoff_ty}>");
        writeln!(
            code,
            "        {:?} => Some(make_ubq_job_factory::<{value_type_expr}, {log_type_expr}>(label, scenario, repeat_index, mode, items_per_producer, batch_size)),",
            label_str,
        )
        .unwrap();
    }

    writeln!(code, "        _ => None,").unwrap();
    writeln!(code, "    }}").unwrap();
    writeln!(code, "}}").unwrap();

    writeln!(code, "fn lookup_ubq_handoff_profile(").unwrap();
    writeln!(code, "    label: &str,").unwrap();
    writeln!(code, "    config: &HandoffProfileConfig,").unwrap();
    writeln!(code, ") -> Option<Result<HandoffProfileResult, String>> {{").unwrap();
    writeln!(code, "    match label {{").unwrap();

    for &(backoff_name, backoff_ty) in BACKOFF_INFO {
        let label_str = format!("balanced,1,page,{backoff_name}");
        let value_type_expr = format!("UBQ<u64, {backoff_ty}>");
        writeln!(
            code,
            "        {:?} => Some(profile_handoff_for::<{value_type_expr}>(\"ubq\", Some(label), config)),",
            label_str,
        )
        .unwrap();
    }

    writeln!(code, "        _ => None,").unwrap();
    writeln!(code, "    }}").unwrap();
    writeln!(code, "}}").unwrap();

    std::fs::write(path, code).expect("failed to write bench_registry.rs");
}

/// The same registry is read by `ab new`, FIFO validation, and Cargo.
fn generate_queue_variants() {
    println!("cargo:rerun-if-changed=src/queue_variants.tsv");
    let root = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    let registry = std::fs::read_to_string(root.join("src/queue_variants.tsv")).unwrap();
    let mut modules = String::new();
    let mut adapters = String::new();
    let mut dispatch = String::from(
        "fn run_registered(cfg: &Config, scenario: &ScenarioConfig, before: Value) -> Option<Result<Value, String>> {\n\
         macro_rules! probe { ($queue:expr) => {{\n\
         if cfg.mode == \"verify\" { run_with::<_, true>($queue, cfg, scenario, before) }\n\
         else { run_with::<_, false>($queue, cfg, scenario, before) }\n\
         }}; }\n",
    );
    let mut names = std::collections::HashSet::new();
    let mut module_names = std::collections::HashSet::new();
    let mut rows: Vec<_> = registry
        .lines()
        .filter(|l| !l.trim().is_empty() && !l.starts_with('#'))
        .collect();
    // A name may extend another queue's geometry prefix; exact variants win.
    rows.sort_by_key(|line| std::cmp::Reverse(line.split('\t').next().unwrap().len()));
    for line in rows {
        let fields: Vec<_> = line.split('\t').collect();
        assert_eq!(fields.len(), 5, "invalid queue registry row: {line}");
        let (name, module, source, adapter, fifo) =
            (fields[0], fields[1], fields[2], fields[3], fields[4]);
        assert!(
            names.insert(name) && module_names.insert(module),
            "duplicate queue registration: {line}"
        );
        assert!(
            matches!(adapter, "ubq" | "v8") && matches!(fifo, "strict" | "relaxed"),
            "invalid queue registration: {line}"
        );
        let implementation = if module == "crate" {
            assert_eq!((name, source, adapter), ("ubq", "src", "ubq"));
            "crate".to_string()
        } else {
            writeln!(
                modules,
                "#[doc = {:?}]\n#[path = {:?}]\npub mod {module};",
                format!("Queue variant `{name}`; registered in src/queue_variants.tsv."),
                root.join(source).join("mod.rs")
            )
            .unwrap();
            format!("crate::{module}")
        };
        let adapter_module = format!("registered_{module}");
        writeln!(
            adapters,
            "mod {adapter_module} {{ use {implementation} as implementation; include!({:?}); }}",
            root.join(format!("src/bench_harness/adapters/{adapter}.rs"))
        )
        .unwrap();
        let queue = if name == "ubq" {
            "ubq".to_string()
        } else {
            format!("ubq-{name}")
        };
        // Every registered queue takes the workload's backoff policy; owned-buffer
        // queues also take their geometry from the queue name.
        if adapter == "v8" {
            writeln!(dispatch,
                "if cfg.queue == {queue:?} || cfg.queue.starts_with(concat!({queue:?}, \"-s\")) {{\n\
                 return Some((|| {{\n\
                 let (slots, vblocks) = parse_geometry(&cfg.queue, {queue:?})?;\n\
                 if cfg.backoff == \"yield\" {{\n\
                 probe!({adapter_module}::Queue::<backoff::Yield>::new(slots, vblocks)?)\n\
                 }} else {{ probe!({adapter_module}::Queue::<backoff::Crossbeam>::new(slots, vblocks)?) }}\n\
                 }})()); }}").unwrap();
        } else {
            writeln!(
                dispatch,
                "if cfg.queue == {queue:?} {{ return Some(if cfg.backoff == \"yield\" {{\n\
                 probe!({adapter_module}::Queue::<backoff::Yield>::new())\n\
                 }} else {{ probe!({adapter_module}::Queue::<backoff::Crossbeam>::new()) }}); }}"
            )
            .unwrap();
        }
    }
    dispatch.push_str("None\n}\n");
    std::fs::write(out.join("queue_modules.rs"), modules).unwrap();
    std::fs::write(out.join("queue_dispatch.rs"), adapters + &dispatch).unwrap();
}
